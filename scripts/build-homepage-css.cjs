/* Build a conservative homepage-only bundle from the shared styles.
   Keep generic rules, keyframes and any selector whose classes/IDs appear in
   either homepage, shared includes, or JS. Preserve pseudo selector groups
   intact rather than dropping negated/optional classes. */
const fs=require('fs'),path=require('path');
const postcss=require('postcss'),parser=require('postcss-selector-parser');
const root=path.resolve(__dirname,'..');
const files=['index.html','es/index.html','assets/includes/header.html','assets/includes/footer.html'];
for(const f of fs.readdirSync(path.join(root,'assets/js')))if(f.endsWith('.js'))files.push('assets/js/'+f);
const source=files.map(f=>fs.readFileSync(path.join(root,f),'utf8')).join('\n');
const escaped=s=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
function keep(selector){
 let valid=true;
 if(selector.toString().includes(':not(')||selector.toString().includes(':is(')||selector.toString().includes(':where('))return true;

 selector.walkAttributes(a=>{if(['data-page-type','data-page-content-group','data-tour-variant'].includes(a.attribute)&&a.operator==='='&& !source.includes(a.attribute+'="'+a.value+'"'))valid=false;});
 if(!valid)return false;
 // Functional selectors can deliberately match missing classes (e.g. :not).
 selector.walkClasses(c=>{if(!new RegExp('(^|[^\\w-])'+escaped(c.value)+'([^\\w-]|$)').test(source))valid=false;});
 selector.walkIds(c=>{if(!new RegExp('(^|[^\\w-])'+escaped(c.value)+'([^\\w-]|$)').test(source))valid=false;});
 return valid;
}
const css=postcss.parse(fs.readFileSync(path.join(root,'assets/css/site.css'),'utf8'));
css.walkRules(rule=>{
 if(rule.parent.type==='atrule'&&/keyframes$/.test(rule.parent.name))return;
 const ast=parser().astSync(rule.selector);const retained=ast.nodes.filter(keep);
 if(!retained.length)rule.remove();else rule.selector=retained.map(x=>x.toString()).join(',');
});
css.walkComments(c=>c.remove());
css.walkAtRules(a=>{if(a.name==='import'||(a.nodes&&!a.nodes.length))a.remove();});
css.walk(n=>{if(n.raws){n.raws.before='';n.raws.after='';n.raws.between=n.type==='decl'?':':'';}});
const result='/* Generated by scripts/build-homepage-css.cjs. Do not edit directly. */\n'+css.toString();
fs.writeFileSync(path.join(root,'assets/css/homepage.css'),result);
console.log('Homepage CSS:',Buffer.byteLength(result),'bytes');
